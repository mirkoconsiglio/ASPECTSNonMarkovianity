# Configuration                                                               #
# --------------------------------------------------------------------------- #
@dataclass
class ModelConfig:
	"""All physical and numerical parameters of the model."""
	
	# Physical parameters
	Gamma: float = 1.0  # overall frequency scale of dissipative dynamics
	Omega: float = 1.0  # intra-reservoir tunnelling / band half-width
	E: float = 0.0  # basis energy
	mu: float = 0.0  # electrochemical potential; a scalar, or one value per T row
	
	# Numerical grids
	tmax: float = 10.0  # maximum evolution time
	nt: int = 101  # number of time points
	Tmax: float = 10.  # maximum temperature
	nT: int = 101  # number of temperature points
	
	# Integration / solver tolerances
	solver_atol: float = 1e-08
	solver_rtol: float = 1e-10
	solver_nsteps: int = 50000
	
	# Frequency-grid resolution for the kernel lookup table (odd -> Simpson).
	# 2049 samples already reproduce the adaptive-quad kernels to ~1e-11 for
	# the default semicircular band; raise it only for very low temperatures
	# (sharper Fermi step) or wider bands.
	n_omega: int = 2049
	
	# Derived grids (filled in __post_init__)
	dt: float = field(default=None, repr=False)
	t: np.ndarray = field(default=None, repr=False)
	T: np.ndarray = field(default=None, repr=False)
	
	def __post_init__(self):
		if self.nt % 2 == 0:
			raise ValueError(f"nt must be odd for cumulative Simpson, got {self.nt}")
		if self.t is None:
			self.t = np.linspace(0.0, self.tmax, self.nt)
		if self.T is None:
			self.T = np.linspace(0.0, self.Tmax, self.nT)
		# noinspection PyTypeChecker
		self.dt = self.t[1] - self.t[0]
		# mu may be given per temperature row, making each row a bath state
		# (T_i, mu_i); see compute_kernels.
		mu = np.asarray(self.mu, dtype=float)
		if mu.ndim > 1 or (mu.ndim == 1 and mu.size != len(self.T)):
			raise ValueError(
				f"mu must be a scalar or have one entry per temperature "
				f"({len(self.T)}), got shape {mu.shape}")


