r"""
non_markovianity.py
===================

Non-Markovianity measures for a 1D spin-chain / single quantum-dot model coupled
to a structured fermionic reservoir (semicircular / Lorentzian spectral density).

The open-system dynamics is generated by a time-local master equation with two
time-dependent rates Lambda_+(t) and Lambda_-(t):

	d rho/dt = -i[H, rho]
			   + Lambda_-(t) D[sigma_-](rho)
			   + Lambda_+(t) D[sigma_+](rho)

The rates are reconstructed from the reservoir noise kernel Phi(t) and the
single-particle propagator G(t):

	Phi(t)   = ∫ dω e^{-iωt} J(ω) f((ω-μ)/T)         (noise kernel)
	G(t)     = ∫ dω e^{-iωt} φ(ω)                     (propagator)
	γ(t)     = Re[ 2i G'(t) / G(t) ] = -d ln|G|^2/dt  (total rate; Gamma_t in code)
	g(ω,t)   = ∫_0^t e^{iωt'} G(t') dt'
	Z(T,t)   = ∫ dω J(ω) f((ω-μ)/T) |g(ω,t)|^2        (noise variance)
	Λ_+(t)   = Ż(T,t) + γ(t) Z(T,t)
	Λ_-(t)   = γ(t) - Λ_+(t)
	G'(t)    = ∫ω e^{-iωt}φ dω = i dG/dt

Five non-Markovianity measures can be computed as a function of temperature T:

	BLP  -- Breuer–Laine–Piilo: backflow of trace distance between an optimal
	        state pair. Temperature independent.
	LPP  -- Lorenzo–Plastina–Paternostro: growth of det A(t) = |G(t)|^4 of the Pauli
	        transfer matrix (volume of accessible states). Temperature independent.
	MSV  -- Megier-Smirne-Vacchini (entropic): backflow of the square root of
            the quantum Jensen-Shannon divergence. Temperature dependent.
	RHPE -- Rivas–Huelga–Plenio, entanglement form: backflow of the concurrence
	        of the Choi state. Temperature dependent.
	RHP  -- Rivas–Huelga–Plenio, divisibility form: negativity of the canonical
	        rates. Temperature dependent.

Each measure integrates the *positive* part of the relevant time derivative.

Performance note
----------------
The reservoir kernels Phi(T,t), G(t) and G'(t) are evaluated with a precomputed
**quadrature lookup table** (see ``compute_kernels``) instead of nT*nt adaptive
``scipy.integrate.quad`` calls. The frequency integral is recast with the
substitution ω = Ω·sin(θ), which removes the semicircular band-edge sqrt
singularity, and the whole Phi(T,t) grid is then obtained from a single matrix
product. This reproduces the original quad result to ~1e-11 while making the
kernel stage ~2000x faster on the default 101x101 grid (≈26 s -> ≈0.01 s).
The number of frequency samples is controlled by ``ModelConfig.n_omega``.

Usage
-----
	python non_markovianity.py --measure all --plot
	python non_markovianity.py --measure BLP LPP --nt 101 --nT 51 --save results
	python non_markovianity.py --measure RHP --Gamma 1.0 --Omega 1.0 --Tmax 10

Or import it:

	from non_markovianity import ModelConfig, NonMarkovianModel
	model = NonMarkovianModel(ModelConfig(nT=51))
	res = model.run(["BLP", "LPP", "RHP"])
	print(res["T"], res["BLP"])

Requires: numpy, scipy, qutip (>=4.6, tested on qutip 5.3). matplotlib only for --plot.
"""

