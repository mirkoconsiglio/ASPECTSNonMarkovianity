def _h2(x):
	"""Binary entropy in bits, with the 0 log 0 = 0 convention. Vectorised."""
	x = np.clip(np.asarray(x, dtype=float), 0.0, 1.0)
	out = np.zeros_like(x)
	m = (x > 0.0) & (x < 1.0)
	out[m] = -x[m] * np.log2(x[m]) - (1.0 - x[m]) * np.log2(1.0 - x[m])
	return out


def _eta(r):
	"""von Neumann entropy (bits) of a qubit with Bloch radius r."""
	return _h2((1.0 + np.clip(np.asarray(r, dtype=float), 0.0, 1.0)) / 2.0)


def _revivals(J):
	"""Accumulated revivals of sqrt(J): sum of positive increments along axis -1.

	Same discretisation as the other *_direct estimators (sum of positive
	differences), so MSV values are comparable with BLP and LPP.
	"""
	d = np.diff(np.sqrt(np.clip(J, 0.0, None)), axis=-1)
	return np.sum(np.clip(d, 0.0, None), axis=-1)


def _grid_pop(n):
	"""Initial occupation pairs p1 > p2 on a n x n grid, shaped (npairs, 1)."""
	p = np.linspace(0.0, 1.0, n)
	P1, P2 = np.meshgrid(p, p, indexing="ij")
	k = P1 > P2
	return P1[k][:, None], P2[k][:, None]


def _grid_disc(n):
	"""(a, w) on the half disc a >= 0, a^2 + w^2 <= 1, shaped (npairs, 1)."""
	a = np.linspace(0.0, 1.0, n)
	w = np.linspace(-1.0, 1.0, 2 * n - 1)
	A, W = np.meshgrid(a, w, indexing="ij")
	k = A ** 2 + W ** 2 <= 1.0
	return A[k][:, None], W[k][:, None]


# --------------------------------------------------------------------------- #
# Bound-state helpers (FIX): a localized level splits off the band when        #
# |E| > Omega - Gamma/2. The excitation distribution then carries a discrete   #
# pole,  phi(w) = phi_continuum(w) + R_b delta(w - w_b)  (Eq. G-bound),  which #
# must be added to the propagator G(t). _sigma is the real-axis self-energy of #
# the semicircular band.                                                       #
# --------------------------------------------------------------------------- #
def _sigma(w, G, O):
	return (G / (2.0 * O)) * (w - np.sign(w) * np.sqrt(w ** 2 - O ** 2))


def _dsigma(w, G, O):
	return (G / (2.0 * O)) * (1.0 - np.sign(w) * w / np.sqrt(w ** 2 - O ** 2))


def bound_states(E, G, O):
	"""Localized levels [(omega_b, residue R_b), ...] with |omega_b| > Omega.
	Onset is |E| = Omega - Gamma/2 (Apollaro parabola h/J = 1 - (J0/J)^2/2)."""
	out = []
	root = lambda w: w - E - _sigma(w, G, O)
	span = O + abs(E) + G + 10.0
	for lo, hi in [(O * (1.0 + 1e-9), span), (-span, -O * (1.0 + 1e-9))]:
		if root(lo) * root(hi) < 0:
			wb = brentq(root, lo, hi, xtol=1e-13)
			# noinspection PyTypeChecker
			Zb = 1.0 / (1.0 - _dsigma(wb, G, O))
			if Zb > 1e-9:
				out.append((wb, Zb))
	return out


