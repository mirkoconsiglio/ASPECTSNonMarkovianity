def save_results(results: Dict[str, np.ndarray], stem: str):
	"""Save results to <stem>.csv and <stem>.npz."""
	keys = [k for k in ("T", "BLP", "LPP", "MSV", "RHP", "RHPE") if k in results]
	data = np.column_stack([results[k] for k in keys])
	header = ",".join(keys)
	np.savetxt(f"{stem}.csv", data, delimiter=",", header=header, comments="")
	np.savez(f"{stem}.npz", **{k: results[k] for k in keys})
	print(f"saved -> {stem}.csv  and  {stem}.npz")


def plot_results(results: Dict[str, np.ndarray], save_to=None):
	"""Plot all measures vs temperature on a single axis with a legend."""
	import matplotlib
	if save_to:
		matplotlib.use("Agg")
	import matplotlib.pyplot as plt
	
	T = results["T"]
	measures = [m for m in VALID_MEASURES if m in results]
	
	fig, ax = plt.subplots(figsize=(6, 4.5))
	for m in measures:
		ax.plot(T, np.asarray(results[m]), marker=".", label=m)
	ax.set_xlabel("Temperature  T")
	ax.set_ylabel(r"$\mathcal{N}$")
	ax.set_title("Non-Markovianity measures")
	ax.legend()
	ax.grid(True, alpha=0.3)
	fig.tight_layout()
	
	if save_to:
		stem = os.path.splitext(save_to)[0]
		fig.savefig(f"{stem}.png", dpi=300)
		fig.savefig(f"{stem}.pdf")  # vector; dpi is irrelevant for PDF output
		print(f"saved plot -> {stem}.png  and  {stem}.pdf")
	else:
		plt.show()


