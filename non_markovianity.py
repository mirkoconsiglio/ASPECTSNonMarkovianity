def _vectorize(A: np.ndarray) -> np.ndarray:
	"""Column-stack a 4x4 matrix into a length-16 vector with the model's
	system<->ancilla index reordering."""
	a = A.copy().T.flatten()
	a[[2, 4]] = a[[4, 2]]
	a[[3, 5]] = a[[5, 3]]
	a[[10, 12]] = a[[12, 10]]
	a[[11, 13]] = a[[13, 11]]
	return a


def _devectorize(a: np.ndarray) -> np.ndarray:
	"""Inverse of :func:`_vectorize`."""
	a = a.copy()
	a[[2, 4]] = a[[4, 2]]
	a[[3, 5]] = a[[5, 3]]
	a[[10, 12]] = a[[12, 10]]
	a[[11, 13]] = a[[13, 11]]
	size = int(np.sqrt(len(a)))
	return a.reshape(size, size)


def _cumsimpson(y, dx, axis=-1):
	"""Cumulative integral, 4th order, same shape as y (y[...,0] -> 0).
	Requires an odd number of samples along `axis`."""
	y = np.moveaxis(y, axis, -1)
	n = y.shape[-1]
	if n < 3 or n % 2 == 0:
		raise ValueError(f"_cumsimpson needs an odd number of samples >= 3, got {n}")
	out = np.zeros_like(y)
	# Simpson over each pair of intervals
	out[..., 2::2] = np.cumsum(
		(y[..., 0:-2:2] + 4.0 * y[..., 1:-1:2] + y[..., 2::2]) * (dx / 3.0), axis=-1)
	# odd points: previous even point + one Simpson 3/8-free half-step
	out[..., 1::2] = out[..., 0:-1:2] + (dx / 12.0) * (
		5.0 * y[..., 0:-1:2] + 8.0 * y[..., 1::2] - y[..., 2::2]
		if n > 2 else 0.0)
	return np.moveaxis(out, -1, axis)


