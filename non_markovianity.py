def _writable_stem(s: str) -> str:
	"""argparse type for output paths: normalise away any extension and create
	the parent directory (if any) so downstream savefig/savetxt cannot fail on a
	missing folder. Returns the bare stem, e.g. 'out/run1.png' -> 'out/run1'
	(with 'out/' created)."""
	stem = os.path.splitext(s)[0]
	d = os.path.dirname(stem)
	if d:
		os.makedirs(d, exist_ok=True)
	return stem


def build_parser() -> argparse.ArgumentParser:
	p = argparse.ArgumentParser(
		description="Compute the BLP, LPP, MSV, RHPE and RHP non-Markovianity measures for the "
		            "1D spin-chain / quantum-dot model.",
		formatter_class=argparse.ArgumentDefaultsHelpFormatter,
	)
	p.add_argument("--measure", "-m", nargs="+", default=["all"],
	               help="Measures to compute: BLP, LPP, MSV, RHPE, RHP, or 'all'.")
	# physics
	p.add_argument("--Gamma", type=float, default=1.0)
	p.add_argument("--Omega", type=float, default=1.0)
	p.add_argument("--E", type=float, default=1.0)
	p.add_argument("--mu", type=float, default=0.0)
	# grids
	p.add_argument("--tmax", type=float, default=80.0)
	p.add_argument("--nt", type=int, default=1001)
	p.add_argument("--Tmax", type=float, default=10.0)
	p.add_argument("--nT", type=int, default=101)
	p.add_argument("--T", "--T-list", dest="T_list", type=float, nargs="+", default=None,
	               help="Explicit list of temperatures, e.g. --T 0 0.5 1 2.5 "
	                    "(overrides --Tmax/--nT, which build a uniform range).")
	p.add_argument("--n-omega", type=int, default=2049,
	               help="Frequency samples for the kernel lookup table (odd).")
	# output
	p.add_argument("--no-plot", action="store_true", help="Do not plot the result.", default=False)
	p.add_argument("--plot-file", type=_writable_stem, default=None,
	               help="Save the plot instead of showing it, as both "
	                    "<stem>.png (raster) and <stem>.pdf (vector); any "
	                    "extension given here is replaced, and the parent "
	                    "directory is created if missing.")
	p.add_argument("--save", type=_writable_stem, default=None,
	               help="Save results to <stem>.csv and <stem>.npz; any extension "
	                    "is replaced and the parent directory is created if missing.")
	p.add_argument("--quiet", "-q", action="store_true",
	               help="Suppress progress messages.")
	p.add_argument("--mesolve", action="store_true", default=False,
	               help="Use the original mesolve route instead of the "
	                    "default direct (mesolve-free) estimators. MSV is then "
	                    "restricted to the polar and equatorial pairs, and RHPE "
	                    "falls back to the direct estimator.")
	
	return p


def main(argv: Sequence[str] | None = None) -> int:
	args = build_parser().parse_args(argv)
	
	measures = [m.upper() for m in args.measure]
	if "ALL" in measures:
		measures = list(VALID_MEASURES)
	
	cfg = ModelConfig(
		Gamma=args.Gamma, Omega=args.Omega, E=args.E, mu=args.mu,
		tmax=args.tmax, nt=args.nt, Tmax=args.Tmax, nT=args.nT,
		T=np.array(args.T_list) if args.T_list is not None else None,
		n_omega=args.n_omega,
	)
	model = NonMarkovianModel(cfg, verbose=not args.quiet)
	results = model.run(measures, direct=not args.mesolve)
	
	model.blp_bound_is_tight()
	model.check_A_of_t()
	
	# Console summary.
	keys = [k for k in ("T", *VALID_MEASURES) if k in results]
	print("\n# " + "  ".join(f"{k:>14}" for k in keys))
	for row in range(len(results["T"])):
		print("  " + "  ".join(f"{results[k][row]:14.6g}" for k in keys))
	
	if args.save:
		save_results(results, args.save)
	if not args.no_plot or args.plot_file:
		plot_results(results, save_to=args.plot_file)
	return 0


if __name__ == "__main__":
	main()
